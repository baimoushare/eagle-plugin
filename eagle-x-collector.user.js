        /**
         * 动态获取 X 当前版本的 GraphQL operation id。
         *
         * X 会随前端发布更新 query id，写死旧值会导致“推文存在但解析为空”。
         * 优先复用页面已经发出的真实请求；没有观察到时再扫描当前 JS 资源；
         * 单推文接口最后保留已知 id 兜底，时间线接口则宁可回退 DOM，也不盲用旧 id。
         */
        getGraphQLOperationId: async function (operationName, fallbackId) {
            this.graphQLOperationCache = this.graphQLOperationCache || {}
            if (this.graphQLOperationCache[operationName]) return this.graphQLOperationCache[operationName]

            const urls = []
            try {
                const resources = performance.getEntriesByType('resource')
                // 当前页面已经发出过同名 GraphQL 请求时，直接复用真实 query id。
                // 这是最可靠来源，比扫描压缩后的 JS bundle 更不容易误判。
                for (let i = resources.length - 1; i >= 0; i--) {
                    const name = String(resources[i]?.name || '')
                    const match = name.match(/\/i\/api\/graphql\/([^/?]+)\/([^?]+)/)
                    if (match && decodeURIComponent(match[2]) === operationName) {
                        this.graphQLOperationCache[operationName] = match[1]
                        return match[1]
                    }
                }
                resources.forEach(entry => {
                    const name = String(entry.name || '')
                    if (/\.js(\?|$)/.test(name) && /(?:x\.com|twitter\.com|twimg\.com)/.test(name)) urls.push(name)
                })
            } catch (err) {}
            try {
                document.querySelectorAll('script[src]').forEach(script => {
                    const src = String(script.src || '')
                    if (/\.js(\?|$)/.test(src)) urls.push(src)
                })
            } catch (err) {}

            const uniqueUrls = Array.from(new Set(urls)).slice(-80).reverse()
            const patterns = [
                new RegExp(`queryId["']?\\s*[:=]\\s*["']([^"']+)["'][\\s\\S]{0,600}${operationName}`),
                new RegExp(`${operationName}[\\s\\S]{0,600}queryId["']?\\s*[:=]\\s*["']([^"']+)["']`),
                new RegExp(`operationName["']?\\s*[:=]\\s*["']${operationName}["'][\\s\\S]{0,800}(?:queryId|id)["']?\\s*[:=]\\s*["']([^"']+)["']`),
                new RegExp(`["']${operationName}["']\\s*,\\s*["']([^"']{10,})["']`),
            ]

            for (const url of uniqueUrls) {
                try {
                    const source = await this.requestTextInBackground(url, {}, 45000).catch(() => '')
                    if (!source || !source.includes(operationName)) continue
                    for (const pattern of patterns) {
                        const match = source.match(pattern)
                        if (match && match[1] && /^[A-Za-z0-9_-]{10,}$/.test(match[1])) {
                            this.graphQLOperationCache[operationName] = match[1]
                            console.debug('[TMD][GraphQL][operation-id]', operationName, match[1], url)
                            return match[1]
                        }
                    }
                } catch (err) {
                    console.debug('[TMD][GraphQL][scan-js-failed]', url, err)
                }
            }

            console.warn('[TMD][GraphQL][operation-id-fallback]', operationName, fallbackId)
            this.graphQLOperationCache[operationName] = fallbackId
            return fallbackId
        },
