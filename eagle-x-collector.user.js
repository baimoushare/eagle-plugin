            const shareButton = btn_group.querySelector(
                'button[data-testid="share"], button[aria-label*="Share"], button[aria-label*="分享"]'
            )
            if (shareButton) {
                return shareButton.closest('div[role="button"]')
                    || shareButton.parentElement
                    || shareButton
            }

            return btn_group.lastElementChild || null
