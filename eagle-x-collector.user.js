            let recognizedTimeline = false
            const visit = (node, depth = 0) => {
                if (!node || typeof node !== 'object' || depth > 22) return
                if (visited.has(node)) return
                visited.add(node)
                if (Array.isArray(node.instructions) || /^TimelineTimeline/.test(String(node.entryType || node.__typename || ''))) {
                    recognizedTimeline = true
                }
                const cursorType = String(node.cursorType || node.cursor_type || '').toLowerCase()
                if (node.value && cursorType) cursors.push({ value: String(node.value), type: cursorType })

                const candidates = [
                    node.tweet_results?.result,
                    node.tweetResults?.result,
                    node.itemContent?.tweet_results?.result,
                    node.content?.itemContent?.tweet_results?.result,
                    node.tweetResult?.result,
                ]
                for (const candidate of candidates) {
                    const tweet = this.unwrapTweetResult(candidate)
                    const id = String(tweet?.rest_id || '').trim()
                    if (tweet && id && !seenIds.has(id)) {
                        seenIds.add(id)
                        tweets.push(tweet)
                    }
                }
                Object.values(node).forEach(child => visit(child, depth + 1))
            }
            visit(payload)
