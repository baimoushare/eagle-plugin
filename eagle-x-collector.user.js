            const segments = Array.isArray(eagle_root_segments) && eagle_root_segments.length > 0
                ? [...eagle_root_segments]
                : ['X']
            const dynamicSegments = this.resolveEagleChildTemplateSegments(pageContext, fallbackHandle)
