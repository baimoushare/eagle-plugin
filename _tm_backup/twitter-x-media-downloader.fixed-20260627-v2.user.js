        resolveEagleChildTemplateSegments: function (pageContext, authorHandle = '') {
            const template = this.getEagleChildTemplateText()
            const author = this.sanitizeFolderSegment(String(authorHandle || '').replace(/^@/, '').trim())
            const tokenMap = {
                '{page-scope}': this.sanitizeFolderSegment(pageContext?.folderScope || ''),
                '{page-type}': this.sanitizeFolderSegment(pageContext?.folderLabel || ''),
                '{page-owner}': this.sanitizeFolderSegment(pageContext?.ownerHandle || ''),
                '{author}': author,
            }

            const rawSegments = String(template || '')
                .split(/[\\/]+/g)
                .map(part => {
                    let next = String(part || '')
                    Object.entries(tokenMap).forEach(([token, value]) => {
                        next = next.split(token).join(value || '')
                    })
                    return this.sanitizeFolderSegment(next)
                })
                .filter(Boolean)

            /**
             * 去掉连续重复段，避免出现：
             * - X / Laobai_Art / Laobai_Art
             * - 书签 / 书签
             */
            const deduped = []
            rawSegments.forEach(segment => {
                if (deduped.length === 0 || deduped[deduped.length - 1] !== segment) {
                    deduped.push(segment)
                }
            })
            return deduped
        },
